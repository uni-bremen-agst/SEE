namespace SEE.Layout.NodeLayouts.EvoStreets
{
    /// <summary>
    /// The absolute orientation of nodes in world space.
    /// </summary>
    internal enum Orientation
    {
        /// <summary>
        /// Z axis to the top.
        /// </summary>
        North,
        /// <summary>
        /// X axis to the right.
        /// </summary>
        East,
        /// <summary>
        /// Z axis to the bottom.
        /// </summary>
        South,
        /// <summary>
        /// X axis to the left.
        /// </summary>
        West
    }
}
